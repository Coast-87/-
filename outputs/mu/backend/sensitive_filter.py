# 特殊匹配规则（不适合简单子串匹配的词）
_EXTRA_PATTERNS = [
    # 独立出现的「SB」辱骂用法；前后不能是字母/数字，因此 USB / SBS 等不会命中
    r"(?<![A-Za-z0-9])SB(?![A-Za-z0-9])",
]

# 编译正则（忽略大小写）
_pattern = re.compile(
    "|".join(re.escape(w) for w in SENSITIVE_WORDS) + "|" + "|".join(_EXTRA_PATTERNS),
    re.IGNORECASE,
)
_whitelist = sorted(WHITELIST_PHRASES, key=len, reverse=True)

# 白名单占位符：罕见汉字，归一化不会删除（符号会被归一化去除，不能用作占位）
_MASK_CHAR = "\u9f98"  # 「龘」

def _normalize(text: str) -> str:
    """归一化文本：全角转半角（NFKC）、去除空白与符号，
    用于识别「傻 逼」「刷-单」「约*炮」「ＳＢ」等插入空格/符号/全角的变体"""
    text = unicodedata.normalize("NFKC", text)
    return re.sub(r"[\s\W_]+", "", text)

def _mask_whitelist(text: str) -> str:
    """将白名单短语占位，避免其中的敏感子串被误判"""
    for phrase in _whitelist:
        if phrase in text:
            text = text.replace(phrase, _MASK_CHAR * len(phrase))
    return text

def check_sensitive(text: str) -> tuple[bool, list[str]]:
    """检查文本是否包含敏感词（含变体），返回 (是否违规, 命中的词列表)"""
    if not text:
        return False, []
    normalized = _normalize(text)
    matches = _pattern.findall(_mask_whitelist(normalized))
    return len(matches) > 0, list(set(matches))

def filter_sensitive(text: str, replacement: str = "***") -> str:
    """将敏感词替换为 replacement（白名单短语保留原样）。
    注意：仅处理原文直接出现的敏感词，变体（加空格/符号）由 check_sensitive 负责拦截。"""
    if not text:
        return text
    tokens = []
    for i, phrase in enumerate(_whitelist):
        token = f"\x00W{i}\x00"
        if phrase in text:
            text = text.replace(phrase, token)
            tokens.append((token, phrase))
    result = _pattern.sub(replacement, text)
    for token, phrase in tokens:
        result = result.replace(token, phrase)
    return result
